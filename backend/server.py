# ---------- Helpers ----------
def _project_dir(project_id: str) -> Path:
    p = STORAGE_DIR / project_id
    p.mkdir(parents=True, exist_ok=True)
    return p


async def _get_project(project_id: str) -> Project:
    doc = await db.projects.find_one({"id": project_id}, {"_id": 0})
    if not doc:
        raise HTTPException(404, "Project not found")
    return Project(**doc)


async def _save_project(project: Project) -> None:
    project.updated_at = datetime.now(timezone.utc).isoformat()
    await db.projects.replace_one({"id": project.id}, project.model_dump(), upsert=True)


async def _update_fields(project_id: str, **fields) -> None:
    fields["updated_at"] = datetime.now(timezone.utc).isoformat()
    await db.projects.update_one({"id": project_id}, {"$set": fields})


# ---------- Cancellation + subprocess render ----------
_render_processes: Dict[str, asyncio.subprocess.Process] = {}


async def _is_cancelled(project_id: str) -> bool:
    """Returns True if the project status is 'cancelled' OR the project no longer exists."""
    doc = await db.projects.find_one({"id": project_id}, {"_id": 0, "status": 1})
    if doc is None:
        return True
    return doc.get("status") == "cancelled"


def _force_kill_pgid(pid: int) -> None:
    import sys
    try:
        if sys.platform == "win32":
            import subprocess
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(pid)], capture_output=True)
        else:
            os.killpg(os.getpgid(pid), signal.SIGKILL)
    except Exception:
        pass


def _terminate_render_proc(proc) -> None:
    """SIGTERM the process group, then SIGKILL after a short grace."""
    import sys
    try:
        if sys.platform == "win32":
            import subprocess
            subprocess.run(["taskkill", "/T", "/PID", str(proc.pid)], capture_output=True)
        else:
            os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
    except Exception:
        return
    try:
        loop = asyncio.get_event_loop()
        loop.call_later(3.0, _force_kill_pgid, proc.pid)
    except RuntimeError:
        pass


async def _run_render_subprocess(
    project_id: str,
    scenes_for_render: List[Dict[str, Any]],
    audio_path: str,
    video_path: str,
    overlay_style: Dict[str, Any],
    audio_duration: float,
    aspect_ratio: str,
    resolution: str = "720p",
    burn_subtitles: bool = True,
) -> None:
    """Run video render in a subprocess so we can SIGTERM it on cancel."""
    payload = json.dumps({
        "scenes": scenes_for_render,
        "audio_path": audio_path,
        "output_path": video_path,
        "overlay_style": overlay_style,
        "audio_duration": audio_duration,
        "aspect_ratio": aspect_ratio,
        "resolution": resolution,
        "burn_subtitles": burn_subtitles,
    })

    runner_path = str(ROOT_DIR / "render_runner.py")
    
    import subprocess
    import sys
    
    kwargs = {}
    if sys.platform == "win32":
        kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP
    else:
        kwargs["start_new_session"] = True

    log_path = ROOT_DIR / f"render_{project_id}.log"
    log_file = open(str(log_path), "w")

    proc = subprocess.Popen(
        [sys.executable, runner_path],
        stdin=subprocess.PIPE,
        stdout=log_file,
        stderr=subprocess.STDOUT,
        cwd=str(ROOT_DIR),
        **kwargs
    )
    _render_processes[project_id] = proc

    assert proc.stdin is not None
    proc.stdin.write(payload.encode("utf-8"))
    proc.stdin.flush()
    proc.stdin.close()

    estimated = max(15.0, float(audio_duration) * 1.2)
    start_t = asyncio.get_event_loop().time()

    try:
        while True:
            if proc.poll() is not None:
                break
            await asyncio.sleep(1.5)

            if await _is_cancelled(project_id):
                _terminate_render_proc(proc)
                raise asyncio.CancelledError("Render cancelled by user")

            elapsed = asyncio.get_event_loop().time() - start_t
            ratio = min(0.99, elapsed / estimated)
            await _update_fields(project_id, progress=85 + int(13 * ratio))

        if proc.returncode != 0:
            err = ""
            if log_path.exists():
                with open(log_path, "r") as f:
                    err = f.read()[-1000:]
            raise RuntimeError(
                f"Render subprocess failed (exit={proc.returncode}): {err}"
            )
    finally:
        try:
            log_file.close()
        except Exception:
            pass
        _render_processes.pop(project_id, None)


# ---------- Pipeline ----------
async def _run_pipeline(project_id: str) -> None:
    try:
        project = await _get_project(project_id)
        pdir = _project_dir(project_id)
        audio_path = str(pdir / project.audio_filename)

        await _update_fields(project_id, status="transcribing", progress=5)
        logger.info("[%s] Transcribing...", project_id)
        result = await transcribe_audio(audio_path)
        if await _is_cancelled(project_id):
            logger.info("[%s] Cancelled during transcription", project_id)
            return
        duration = result["duration"]
        visual_concept = result.get("visual_concept", "")
        timing_engine = result.get("timing_engine", "gemini")

        # Use new sentence scene builder (one sentence per scene = one image = one caption)
        scene_dicts = scene_builder.build_sentence_scenes(
            result["segments"], duration, title=project.name
        )

        scenes = [
            Scene(
                idx=i,
                start=s["start"],
                end=s["end"],
                text=s["text"],
                text_start=s.get("text_start"),
                text_end=s.get("text_end"),
                kind=s["kind"],
                words=s.get("words", []),
            )
            for i, s in enumerate(scene_dicts)
        ]

        if not scenes:
            raise RuntimeError("No speech detected in audio")

        # Step 2: Art director LLM prompt pass (Claude / OpenAI / Gemini / Grok)
        art_prompts = await generate_art_director_prompts(
            scene_dicts,
            visual_concept=visual_concept,
            song_title=project.name,
            style=project.style,
            custom_style=project.custom_style,
            prompt_provider=project.prompt_provider,
        )
        for s in scenes:
            if s.idx in art_prompts:
                s.art_director_prompt = art_prompts[s.idx]

        await _update_fields(
            project_id,
            audio_duration=duration,
            visual_concept=visual_concept,
            timing_engine=timing_engine,
            scenes=[s.model_dump() for s in scenes],
            status="generating_images",
            progress=20,
        )
        logger.info(
            "[%s] %d sentence scenes (lyric=%d, title=%d, instrumental=%d). Generating images via %s...",
            project_id, len(scenes),
            sum(1 for s in scenes if s.kind == "lyric"),
            sum(1 for s in scenes if s.kind == "title"),
            sum(1 for s in scenes if s.kind == "instrumental"),
            project.image_provider,
        )

        sem = asyncio.Semaphore(4)
        completed_count = {"n": 0}
        chorus_cache: Dict[str, List[str]] = {}

        async def gen_one(scene: Scene) -> None:
            if await _is_cancelled(project_id):
                return

            # Check chorus reuse cache if enabled
            cache_key = scene_builder.text_key(scene.text) if (project.reuse_chorus_images and scene.kind == "lyric") else ""
            if cache_key and cache_key in chorus_cache:
                cached_files = chorus_cache[cache_key]
                # Copy or reference existing images
                reused_filenames = []
                for k, src_name in enumerate(cached_files):
                    dst_name = f"scene_{scene.idx:04d}.png" if k == 0 else f"scene_{scene.idx:04d}_{k}.png"
                    src_p = pdir / src_name
                    dst_p = pdir / dst_name
                    if src_p.exists() and not dst_p.exists():
                        shutil.copyfile(src_p, dst_p)
                    reused_filenames.append(dst_name if dst_p.exists() else src_name)
                scene.image_filenames = reused_filenames
                scene.image_filename = reused_filenames[0]
                scene.image_status = "completed"
                completed_count["n"] += 1
                progress = 20 + int(60 * completed_count["n"] / max(1, len(scenes)))
                await _update_fields(project_id, scenes=[s.model_dump() for s in scenes], progress=progress)
                logger.info("[%s] Reused chorus image for scene %d (%s)", project_id, scene.idx, scene.text[:30])
                return

            async with sem:
                if await _is_cancelled(project_id):
                    return
                # Title and instrumental scenes only need 1 image
                n_imgs = 1 if scene.kind != "lyric" else max(1, min(3, project.images_per_scene))
                filenames: List[str] = []
                try:
                    for k in range(n_imgs):
                        out_name = (
                            f"scene_{scene.idx:04d}.png" if k == 0
                            else f"scene_{scene.idx:04d}_{k}.png"
                        )
                        out_path = str(pdir / out_name)
                        await generate_scene_image(
                            scene.text, out_path,
                            scene.style_override or project.style,
                            project.aspect_ratio,
                            custom_style=project.custom_style,
                            variation_idx=k,
                            image_size=project.image_quality,
                            song_context=visual_concept,
                            scene_kind=scene.kind,
                            song_title=project.name,
                            art_director_prompt=scene.art_director_prompt,
                            image_provider=project.image_provider,
                        )
                        filenames.append(out_name)
                    scene.image_filenames = filenames
                    scene.image_filename = filenames[0]
                    scene.image_status = "completed"
                    if cache_key and filenames:
                        chorus_cache[cache_key] = filenames
                except Exception as exc:
                    logger.exception("Image gen failed for scene %d: %s", scene.idx, exc)
                    if filenames:
                        scene.image_filenames = filenames
                        scene.image_filename = filenames[0]
                        scene.image_status = "completed"
                    else:
                        scene.image_status = "failed"

            completed_count["n"] += 1
            progress = 20 + int(60 * completed_count["n"] / max(1, len(scenes)))
            await _update_fields(
                project_id,
                scenes=[s.model_dump() for s in scenes],
                progress=progress,
            )

        await asyncio.gather(*(gen_one(s) for s in scenes))

        if await _is_cancelled(project_id):
            logger.info("[%s] Cancelled after image gen", project_id)
            return

        # Render video
        if await _is_cancelled(project_id):
            logger.info("[%s] Cancelled before render", project_id)
            return
        await _update_fields(project_id, status="rendering", progress=85)
        logger.info("[%s] Rendering video...", project_id)
        project = await _get_project(project_id)
        scenes_for_render = []
        for s in project.scenes:
            paths = [str(pdir / f) for f in (s.image_filenames or ([s.image_filename] if s.image_filename else []))]
            if paths:
                scenes_for_render.append({
                    "start": s.start,
                    "end": s.end,
                    "text": s.text,
                    "text_start": s.text_start,
                    "text_end": s.text_end,
                    "image_paths": paths,
                    "words": s.words,
                    "overlay_override": s.overlay_override,
                })

        clean_name = "music_video_clean.mp4"
        clean_path = str(pdir / clean_name)
        await _run_render_subprocess(
            project_id,
            scenes_for_render,
            audio_path,
            clean_path,
            project.overlay_style,
            project.audio_duration,
            project.aspect_ratio,
            project.resolution,
            False,  # initial pipeline ALWAYS renders clean — user iterates on the live overlay in the editor and re-renders to bake
        )

        video_name = "music_video.mp4"
        video_path = pdir / video_name
        shutil.copyfile(clean_path, str(video_path))

        srt_name = "subtitles.srt"
        srt_path = pdir / srt_name
        srt_path.write_text(
            build_srt([{"start": s.start, "end": s.end, "text": s.text} for s in project.scenes]),
            encoding="utf-8",
        )

        await _update_fields(
            project_id,
            video_filename=video_name,
            clean_video_filename=clean_name,
            srt_filename=srt_name,
            last_render_burn_subtitles=False,
            clean_video_stale=False,
            status="completed",
            progress=100,
        )
        logger.info("[%s] Pipeline complete", project_id)

    except asyncio.CancelledError:
        logger.info("[%s] Pipeline cancelled by user", project_id)
        await _update_fields(project_id, status="cancelled")
        return
    except Exception as exc:
        logger.exception("Pipeline failed for %s", project_id)
        await _update_fields(project_id, status="failed", error_message=str(exc))


async def _render_only(project_id: str) -> None:
    try:
        await _update_fields(project_id, status="rendering", progress=85)
        project = await _get_project(project_id)
        pdir = _project_dir(project_id)
        audio_path = str(pdir / project.audio_filename)

        scenes_for_render = []
        for s in project.scenes:
            paths = [str(pdir / f) for f in (s.image_filenames or ([s.image_filename] if s.image_filename else []))]
            if paths:
                scenes_for_render.append({
                    "start": s.start,
                    "end": s.end,
                    "text": s.text,
                    "text_start": s.text_start,
                    "text_end": s.text_end,
                    "image_paths": paths,
                    "words": s.words,
                    "overlay_override": s.overlay_override,
                })

        if not scenes_for_render:
            raise RuntimeError("No scenes with images available to render")

        clean_name = "music_video_clean.mp4"
        clean_path = pdir / clean_name
        video_name = "music_video.mp4"
        video_path = pdir / video_name

        # If a legacy clean video was stored as music_video.mp4, preserve it
        if not clean_path.exists() and video_path.exists() and not getattr(project, "last_render_burn_subtitles", False):
            try:
                shutil.copyfile(str(video_path), str(clean_path))
            except Exception:
                pass

        # Check if we can perform an ultra-fast FFmpeg subtitle bake (~5-10s)
        can_fast_bake = clean_path.exists() and not getattr(project, "clean_video_stale", False)

        if can_fast_bake:
            if project.burn_subtitles:
                logger.info("[%s] Fast baking subtitles with native FFmpeg in ~5-10s...", project_id)
                await asyncio.to_thread(
                    burn_subtitles_fast,
                    str(clean_path),
                    scenes_for_render,
                    project.overlay_style,
                    str(video_path),
                    project.aspect_ratio,
                    project.resolution,
                )
                last_burn = True
            else:
                if not (clean_path.resolve() == video_path.resolve()):
                    shutil.copyfile(str(clean_path), str(video_path))
                last_burn = False
        else:
            # Full render needed (e.g. repainted scene images or changed scene start times)
            logger.info("[%s] Rendering full clean video clips...", project_id)
            await _run_render_subprocess(
                project_id,
                scenes_for_render,
                audio_path,
                str(clean_path),
                project.overlay_style,
                project.audio_duration,
                project.aspect_ratio,
                project.resolution,
                False,  # always render clean base video
            )
            if project.burn_subtitles:
                logger.info("[%s] Fast baking subtitles onto newly rendered clean video...", project_id)
                await asyncio.to_thread(
                    burn_subtitles_fast,
                    str(clean_path),
                    scenes_for_render,
                    project.overlay_style,
                    str(video_path),
                    project.aspect_ratio,
                    project.resolution,
                )
                last_burn = True
            else:
                shutil.copyfile(str(clean_path), str(video_path))
                last_burn = False

        srt_name = "subtitles.srt"
        (pdir / srt_name).write_text(
            build_srt([{"start": s.start, "end": s.end, "text": s.text} for s in project.scenes]),
            encoding="utf-8",
        )

        await _update_fields(
            project_id,
            video_filename=video_name,
            clean_video_filename=clean_name,
            srt_filename=srt_name,
            last_render_burn_subtitles=last_burn,
            clean_video_stale=False,
            status="completed",
            progress=100,
        )
        logger.info("[%s] Render completed (burn=%s)", project_id, last_burn)
    except asyncio.CancelledError:
        logger.info("[%s] Re-render cancelled by user", project_id)
        await _update_fields(project_id, status="cancelled")
    except Exception as exc:
        logger.exception("Re-render failed for %s", project_id)
        await _update_fields(project_id, status="failed", error_message=str(exc))


