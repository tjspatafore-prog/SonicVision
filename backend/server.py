# ---------- Models ----------
class Scene(BaseModel):
    idx: int
    start: float
    end: float
    text: str
    text_start: Optional[float] = None  # tight caption appearance time
    text_end: Optional[float] = None    # tight caption hide time
    art_director_prompt: Optional[str] = None  # custom prompt generated by art director LLM
    image_filename: Optional[str] = None  # backward-compat: first image
    image_filenames: List[str] = Field(default_factory=list)  # multi-image-per-scene
    image_status: str = "pending"  # pending, generating, completed, failed
    style_override: Optional[str] = None  # per-scene image-style preset override
    kind: str = "lyric"  # "lyric" | "title" | "instrumental"
    words: List[Dict[str, Any]] = Field(default_factory=list)  # [{"text": "...", "start": s, "end": s}, ...]
    overlay_override: Optional[Dict[str, Any]] = None  # per-scene typography override (font_family, font_color, font_size)


class Project(BaseModel):
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    name: str
    audio_filename: str
    audio_duration: float = 0.0
    phrase_grouping: int = 1
    images_per_scene: int = 1  # 1, 2 or 3
    style: str = "cinematic"
    custom_style: Optional[str] = None
    aspect_ratio: str = "16:9"
    resolution: str = "720p"  # "720p" or "1080p"
    image_quality: str = "low"  # "low", "medium", "high"
    image_provider: str = Field(default_factory=providers.default_image_provider)  # "grok" | "gemini" | "openai"
    prompt_provider: str = Field(default_factory=providers.default_prompt_provider)  # "claude" | "openai" | "gemini" | "grok" | "none"
    timing_engine: str = "gemini"  # "deepgram" | "whisper" | "gemini"
    reuse_chorus_images: bool = True  # reuse identical chorus images for economical generation
    burn_subtitles: bool = True  # default to true for final video bake
    last_render_burn_subtitles: bool = False
    visual_concept: str = ""  # 2-4 sentence song-wide visual world, derived from audio
    status: str = "created"  # created, transcribing, generating_images, rendering, completed, failed, cancelled
    progress: int = 0  # 0-100
    error_message: Optional[str] = None
    scenes: List[Scene] = Field(default_factory=list)
    overlay_style: Dict[str, Any] = Field(default_factory=lambda: dict(DEFAULT_OVERLAY))
    video_filename: Optional[str] = None
    clean_video_filename: Optional[str] = None
    clean_video_stale: bool = False
    srt_filename: Optional[str] = None
    teaser_status: str = "none"  # none, generating, completed, failed
    teaser_files: Dict[str, str] = Field(default_factory=dict)  # {"9:16": "teaser_9_16.mp4", ...}
    teaser_error: Optional[str] = None
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


